/** Composite-key index: "\${topicSlug}|||\${subtopicSlug}" → entry. */
const BY_COMPOSITE = new Map<string, GoldManifestEntry>();
/** Fallback index: subtopicSlug → entries (may collide across topics). */
const BY_SUBTOPIC = new Map<string, GoldManifestEntry[]>();
